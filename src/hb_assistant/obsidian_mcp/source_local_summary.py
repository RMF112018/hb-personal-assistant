SOURCE_CARD_HEADINGS: tuple[str, ...] = (
    "Summary", "Key Extracted Details", "PM Attention", "Follow-Up Questions", "Limits / Uncertainty")

SOURCE_CARD_SUMMARY_SYSTEM_PROMPT = (
    "You are writing an ADVISORY second-brain summary of a construction SOURCE DOCUMENT for a project "
    "manager.\n"
    "Ground EVERY statement in the SOURCE EXCERPT and DOCUMENT TITLE provided — not in the card's "
    "classifier label.\n"
    "The CLASSIFIER HINT (document_type) MAY BE WRONG. Identify what the document ACTUALLY is from its "
    "own title/header/content: a generic specification or template, a tracking/value-analysis log, a "
    "transmittal, a memo / clarification / open-questions list, or a project-specific instrument.\n"
    "If the content contradicts the classifier hint, identify the TRUE nature and NOTE THE MISMATCH in "
    "### Limits / Uncertainty; do NOT assert the classifier's label as fact (e.g. do not call a "
    "value-analysis tracking log a 'warranty').\n"
    "Extract concrete specifics from the source: dates, statuses, spec section numbers, line-item "
    "categories, document identifiers, key requirements, and unresolved questions. Mention data/table "
    "quality problems if visible (e.g. #REF errors). If the document is a generic/template "
    "specification, SAY SO and do not claim project-specific tailoring the text does not support.\n"
    "Do NOT invent amounts, statuses, dates, parties, or project-specific facts. Use 'Unknown' or 'Not "
    "stated' where the source is silent.\n"
    "Output CONCISE Markdown only — no code fences, HTML comments, YAML, tables, links, or file paths.\n"
    "Use EXACTLY these five sections, in this order:\n"
    "_Advisory — locally generated by qwen2.5:14b. Verify against the source before relying on this "
    "summary._\n\n"
    "### Summary\n<what the document actually is, why it exists, and whether it is generic/template, a "
    "log/tracker, a transmittal, a memo/questions list, or project-specific>\n\n"
    "### Key Extracted Details\n- <dates / statuses / spec sections / line-item categories / identifiers "
    "/ major requirements / data-quality issues such as #REF>\n\n"
    "### PM Attention\n- <concrete review actions, missing dispositions, values/statuses to verify, "
    "contract/submittal/scope implications>\n\n"
    "### Follow-Up Questions\n- <specific unresolved questions grounded in the source>\n\n"
    "### Limits / Uncertainty\n- <extraction issues, classification mismatch, generic/template status, "
    "truncation, table/OCR risk>\n"
)


def build_source_card_summary_prompt(card_text: str, detail: dict, *, title: str,
                                     document_type: str | None, max_input_chars: int) -> str:
    """Source-grounded prompt: the SOURCE EXCERPT + TITLE are primary; the classifier is a hint."""
    body = _strip_local_summary_block(_strip_frontmatter(card_text)).strip()
    excerpt = str(detail.get("text_excerpt") or "").strip()
    parts = [
        f"DOCUMENT TITLE: {title}",
        f"CLASSIFIER HINT (may be wrong): document_type={document_type or 'unknown'}",
        "",
        "PRIMARY EVIDENCE — SOURCE EXCERPT (ground your summary in the document's own text below):",
    ]
    if excerpt and not detail.get("text_vault_ref"):
        parts.append(excerpt[:max(0, int(max_input_chars))])
    else:
        parts.append("(no source excerpt available — note this in Limits / Uncertainty and keep the "
                     "summary minimal)")
    parts += ["",
              "SECONDARY CONTEXT — deterministic source card (its classifier label may be wrong):",
              "", body, "",
              "Write the five-section advisory now, grounded in the SOURCE EXCERPT and TITLE."]
    return "\n".join(parts)


_SPEC_SECTION_RE = re.compile(r"\b\d\d[\s-]\d\d[\s-]\d\d\b")  # e.g. 02 87 13 / 02-87-13
_GROUND_STOP = frozenset({
    "this", "that", "with", "from", "have", "will", "your", "there", "which", "their", "about",
    "document", "source", "card", "project", "summary", "advisory", "please", "shall", "these",
    "them", "then", "than", "into", "over", "under", "such", "been", "were", "when", "what",
    "unknown", "stated", "none", "detail", "details", "generated", "local", "verify",
})


def _content_tokens(text: str) -> set[str]:
    return {w for w in re.findall(r"[a-z0-9#]{4,}", str(text or "").lower()) if w not in _GROUND_STOP}


def _title_signal(title: str, excerpt: str) -> str | None:
    """Deterministic document-family signal from the title + excerpt header (never body-only guess)."""
    ttok = set(re.sub(r"[^a-z0-9]+", " ", str(title or "").lower()).split())
    head = (str(title or "") + "\n" + str(excerpt or "")[:1200]).lower()
    hnorm = re.sub(r"[^a-z0-9]+", " ", head)
    if ("va" in ttok and ("log" in ttok or "tracking" in ttok)) or "value analysis" in hnorm \
            or "value engineering" in hnorm:
        return "value_analysis_log"
    if _SPEC_SECTION_RE.search(head) or "masterworks" in hnorm or "master works" in hnorm \
            or "specification" in hnorm or "part 1 general" in hnorm or "part 2 products" in hnorm:
        return "specification_generic"
    if re.search(r"clarification|open items|open questions|memorandum|preconstruction question", hnorm) \
            or " memo " in f" {hnorm} " or head.count("?") >= 2:
        return "memo_questions"
    if "transmittal" in hnorm:
        return "transmittal"
    if "warranty" in hnorm or "warrant" in ttok:
        return "warranty"
    if "tracking" in hnorm or "log" in ttok:
        return "tracker"
    return None


# document_type values that CONTRADICT a detected family (surface, don't repair, in this pass).
_FAMILY_CONFLICTS = {
    "value_analysis_log": {"warranty", "contract", "submittal"},
    "specification_generic": {"submittal", "scope_of_work", "warranty", "contract"},
    "memo_questions": {"scope_of_work", "contract", "submittal", "warranty"},
    "transmittal": {"scope_of_work", "contract"},
}
# For a detected family, the summary must satisfy EACH required signal group (>=1 match per group).
_FAMILY_REQUIRED: dict[str, list[str]] = {
    "value_analysis_log": [r"value[- ]?analysis|value engineering|\bva\b|tracking log|value tracking",
                           r"line[- ]?item|status|value|alternate"],
    "specification_generic": [r"generic|template|specification|spec package|standard|master ?works",
                              r"clean|kill|coat|moisture|iicrc|s\s?520|submittal|sds|voc|product|"
                              r"manufacturer|remediation"],
    "memo_questions": [r"clarification|question|open item|preconstruction|unresolved|"
                       r"to be (confirmed|determined)|\bmemo\b"],
}


def detect_classification_conflict(document_type: str | None, title: str, excerpt: str) -> str | None:
    """Return the true document family when title/content contradict document_type, else None."""
    fam = _title_signal(title, excerpt)
    if fam and str(document_type or "").lower() in _FAMILY_CONFLICTS.get(fam, set()):
        return fam
    return None


def _section_bullets(lines: list[str], heading: str) -> list[str]:
    out, cap = [], False
    for ln in lines:
        m = _HEADING_RE.match(ln)
        if m:
            cap = m.group("text").strip() == heading
            continue
        if cap and ln.strip():
            txt = ln.strip().lstrip("-*").strip()
            if txt and txt.lower() not in ("none", "n/a", "not stated", "unknown", "not detected"):
                out.append(txt)
    return out


def validate_summary_quality(lines: list[str], detail: dict | None = None, *, title: str = "",
                             document_type: str | None = None) -> tuple[bool, str]:
    """Strict source-card summary gate: five-section shape + metadata/grounding/classification checks.

    Returns ``(ok, reason)``. Reject reasons: ``metadata_conflict`` (filename/size/type assertion),
    ``format_invalid`` / ``noncanonical_shape`` (five-section shape), ``thin_key_details``,
    ``ungrounded`` (not grounded in the source excerpt), ``classification_conflict`` (parrots a
    contradicted classifier label — e.g. VA log as warranty), ``generic_spec_unqualified``,
    ``missing_data_quality_note`` (excerpt has #REF but summary omits it), and
    ``missing_required_family_signal`` (detected family's required content absent). Pure/deterministic.
    """
    detail = detail or {}
    excerpt = str(detail.get("text_excerpt") or "")
    # 1. metadata contradiction (reuse the four-section path's filename/size/type-family checks)
    fam_type = _deterministic_type_family(detail)
    for ln in lines:
        if _FILENAME_ASSERT_RE.match(ln) or _SIZE_ASSERT_RE.search(ln):
            return False, "metadata_conflict"
        if fam_type:
            for tok in _TYPE_TOKEN_RE.findall(ln):
                if _TYPE_FAMILY.get(tok.lower()) not in (None, fam_type):
                    return False, "metadata_conflict"
    # 2. five-section shape
    headings = [m.group("text").strip() for ln in lines if (m := _HEADING_RE.match(ln))]
    hset = set(headings)
    if any(h not in hset for h in SOURCE_CARD_HEADINGS):
        return False, "format_invalid"
    canon = set(SOURCE_CARD_HEADINGS)
    if any(h not in canon for h in headings) or any(headings.count(h) > 1 for h in SOURCE_CARD_HEADINGS):
        return False, "noncanonical_shape"
    if sum(1 for ln in lines if _ADVISORY_PREAMBLE_RE.match(ln)) > 1:
        return False, "noncanonical_shape"
    if any(_BOLD_LABEL_RE.match(ln) for ln in lines):
        return False, "noncanonical_shape"
    # 3. thin Key Extracted Details
    if not _section_bullets(lines, "Key Extracted Details"):
        return False, "thin_key_details"
    blow = "\n".join(lines).lower()
    # 4. grounding in the source excerpt (skipped only when no excerpt is available)
    if excerpt.strip():
        meta = _content_tokens(f"{title} {document_type}")
        shared = (_content_tokens(excerpt) - meta) & (_content_tokens(blow) - meta)
        if len(shared) < 3:
            return False, "ungrounded"
    fam = _title_signal(title, excerpt)
    # 5. classification conflict — must not parrot a contradicted label (VA log summarized as warranty)
    if fam == "value_analysis_log" and re.search(r"warrant", blow) and not re.search(
            r"value[- ]?analysis|value engineering|\bva\b|tracking log|value tracking", blow):
        return False, "classification_conflict"
    # 6. generic-spec must be qualified as generic/template (not a bare project-specific submittal)
    if fam == "specification_generic":
        if not re.search(r"generic|template|specification|spec package|standard|master ?works", blow):
            return False, "generic_spec_unqualified"
        if re.search(r"project[- ]specific submittal", blow) and not re.search(r"generic|template", blow):
            return False, "generic_spec_unqualified"
    # 7. table/data-quality — surface #REF when the excerpt contains it
    if "#ref" in excerpt.lower() and "#ref" not in blow \
            and not re.search(r"\bref\b|table|data[- ]quality|value verification", blow):
        return False, "missing_data_quality_note"
    # 8. required family signals (each group must have >=1 match)
    for pattern in _FAMILY_REQUIRED.get(fam or "", []):
        if not re.search(pattern, blow):
            return False, "missing_required_family_signal"
    return True, "ok"
