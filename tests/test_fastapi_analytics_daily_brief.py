"""Prompt 10/14 — Daily Brief external-agent Markdown analytics shell tests.

Covers the FastAPI route surface + service contract for the "present/polish only"
external Daily Brief workflow. The app detects a Markdown file generated by an
external desktop AI platform (Claude / ChatGPT / Perplexity / Other), validates
freshness, parses light sections when practical, and presents a polished view.
The app never authors or rewrites the substantive content.

These tests are intentionally hermetic for the core contract:
- generate-setup-instructions is pure (no FS side effects for the four platforms).
- configure + status/detect paths exercise the local config JSON and the
  missing-file / waiting states without requiring a pre-existing real brief on disk.
- A lightweight parser + raw-preservation test uses a controlled temp folder + file
  so that source Markdown is shown to be preserved and sections are derived.
"""

from __future__ import annotations

import hashlib
import json
import os
import shutil
import tempfile
import time
from pathlib import Path
from typing import Any

import pytest

pytest.importorskip("fastapi")

from fastapi.testclient import TestClient

from hb_assistant.construction.analytics import create_app
from hb_assistant.store.migrator import SQLiteMigrator

FORBIDDEN = (
    "BEGIN PRIVATE KEY",
    "access_token",
    "refresh_token",
    "client_secret",
    "raw_body",
    "raw_document_text",
    "raw_calendar_payload",
    "raw_prompt",
    "raw_response",
    "signed_url",
    "download_url",
)


def _client(tmp_path: Path) -> TestClient:
    db = str(tmp_path / "daily_brief.sqlite")
    SQLiteMigrator(db_path=db).apply()
    return TestClient(create_app(db_path=db))


def _assert_safe(payload: Any) -> None:
    serialized = json.dumps(payload, default=str)
    for marker in FORBIDDEN:
        assert marker not in serialized


def test_daily_brief_status_and_settings_alias_are_safe(tmp_path: Path) -> None:
    client = _client(tmp_path)
    for path in ("/api/daily-brief/status", "/api/settings/daily-brief"):
        r = client.get(path)
        assert r.status_code == 200
        data = r.json()
        _assert_safe(data)
        # Guardrails present on API surfaces
        if "guardrails" in data:
            g = data["guardrails"] or {}
            if "no_raw_sensitive_response_fields" in g:
                assert g.get("no_raw_sensitive_response_fields") is True
            if "read_only" in g:
                assert g.get("read_only") is True


