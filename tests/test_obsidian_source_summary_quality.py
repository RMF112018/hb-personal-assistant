def test_va_log_summarized_as_warranty_rejected():
    ok, reason = sls.validate_summary_quality(
        _lines(_VA_BAD), {"text_excerpt": _VA_EXCERPT}, title=_VA_TITLE, document_type="warranty")
    assert not ok and reason == "classification_conflict"


def test_va_log_grounded_value_analysis_summary_ok():
    ok, reason = sls.validate_summary_quality(
        _lines(_VA_GOOD), {"text_excerpt": _VA_EXCERPT}, title=_VA_TITLE, document_type="warranty")
    assert ok and reason == "ok"


