# --------------------------------------------------------------------------- cross-cutting gates
def test_four_section_shape_rejected_as_format_invalid():
    # Old four-section advisory (no "Key Extracted Details") is invalid for source cards.
    four = (
        "_Advisory_\n\n### Summary\nx grounded glazing roofing membrane.\n\n"
        "### PM Attention\n- a\n\n### Follow-Up Questions\n- b\n\n### Limits / Uncertainty\n- c\n")
    ok, reason = sls.validate_summary_quality(
        _lines(four), {"text_excerpt": _VA_EXCERPT}, title="x", document_type="rfi")
    assert not ok and reason == "format_invalid"


def test_ungrounded_when_summary_ignores_excerpt():
    generic = (
        "_Advisory_\n\n### Summary\nA generic administrative document.\n\n"
        "### Key Extracted Details\n- General routine content only.\n\n"
        "### PM Attention\n- Nothing specific.\n\n### Follow-Up Questions\n- None.\n\n"
        "### Limits / Uncertainty\n- Advisory only.\n")
    ok, reason = sls.validate_summary_quality(
        _lines(generic), {"text_excerpt": _VA_EXCERPT}, title="x", document_type="rfi")
    assert not ok and reason == "ungrounded"


def test_missing_ref_data_quality_note_rejected():
    # Excerpt has #REF; a grounded VA summary that omits any #REF/data-quality note is rejected.
    no_ref = (
        "_Advisory_\n\n### Summary\nA value-analysis tracking log of alternates and their status.\n\n"
        "### Key Extracted Details\n- Line items: glazing, roofing membrane, HVAC controls.\n"
        "- Statuses: open, accepted, rejected.\n\n"
        "### PM Attention\n- Confirm each alternate value and status.\n\n"
        "### Follow-Up Questions\n- Which alternates remain open?\n\n"
        "### Limits / Uncertainty\n- Value-analysis log; values need verification.\n")
    ok, reason = sls.validate_summary_quality(
        _lines(no_ref), {"text_excerpt": _VA_EXCERPT}, title=_VA_TITLE, document_type="warranty")
    assert not ok and reason == "missing_data_quality_note"
